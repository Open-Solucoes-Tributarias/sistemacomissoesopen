-- ============================================================
-- Migração 29 — Marketing: lista de leads (LinkedIn)
-- ============================================================
--
-- As redes guardam "um número por mês" (seguidores, impressões...). Lead é
-- outra natureza: uma pessoa por linha, com nome, cargo, a empresa dela e se
-- essa empresa é órgão público. Por isso tabela própria, e não mais um
-- indicador dentro de marketing_metricas.
--
-- Nome, cargo e empresa são os três campos que o LinkedIn exporta juntos, e
-- os três que decidem se vale abordar: quem é, que poder de decisão tem, e
-- onde trabalha.
--
-- Por que "órgão público" importa aqui: a carteira da Open é cheia de MP,
-- TRE, TRT, INPI — órgão público compra por licitação, com ciclo e
-- interlocutor diferentes de empresa privada. Separar os dois na origem
-- muda como o lead é trabalhado.
--
-- `orgao_publico` é BOOLEAN NULL de propósito: três estados. null = ainda
-- não classificado (é como o lead nasce na importação), true = órgão
-- público, false = não é. O mesmo desenho de `rentavel` em
-- contratos_consultoria e de `renovado` em renovacoes — sem isso, "não
-- classificado" e "não é órgão público" virariam a mesma coisa.
--
-- `rede` fica na tabela mesmo a tela só oferecendo LinkedIn hoje: lead de
-- outra origem cabe aqui sem migração nova.
create table if not exists marketing_leads (
  id bigint generated by default as identity primary key,
  ano int not null,
  mes text not null,
  rede text not null default 'linkedin',
  nome text not null default '',
  cargo text not null default '',
  empresa text not null default '',
  orgao_publico boolean,
  created_at timestamptz not null default now()
);

-- A lista é consultada por ano/rede ao montar o painel.
create index if not exists marketing_leads_ano_rede_idx on marketing_leads(ano, rede);

alter table marketing_leads enable row level security;

-- Mesmo corte das outras tabelas de marketing: a equipe toda lê, só quem
-- administra escreve. Lead não é dado de comissão, então não há máscara por
-- pessoa aqui.
drop policy if exists "select any" on marketing_leads;
create policy "select any" on marketing_leads for select to authenticated
  using (true);

drop policy if exists "insert admin" on marketing_leads;
create policy "insert admin" on marketing_leads for insert to authenticated
  with check (current_user_is_admin());

drop policy if exists "update admin" on marketing_leads;
create policy "update admin" on marketing_leads for update to authenticated
  using (current_user_is_admin());

drop policy if exists "delete admin" on marketing_leads;
create policy "delete admin" on marketing_leads for delete to authenticated
  using (current_user_is_admin());

revoke all on marketing_leads from anon;
grant select on marketing_leads to authenticated;
grant insert, update, delete on marketing_leads to authenticated;
grant usage on sequence marketing_leads_id_seq to authenticated;
