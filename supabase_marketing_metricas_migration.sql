-- ============================================================
-- Migração 24 — Marketing: crescimento das redes sociais
-- ============================================================
-- Aplicada no banco como: marketing_metricas
--
-- Marketing também é equipe: fica ao lado do Relatório de Desempenho e
-- de Bônus e Metas, no menu. Acompanha o crescimento de Instagram,
-- YouTube, LinkedIn, TikTok e PodTributar, nas duas contas que a empresa
-- mantém — Open e Foco Tributário —, pra apresentar ao dono da empresa.
--
-- Não é dado de comissão nem de contrato — é o número que ela mostra
-- pro dono. Por isso a leitura fica aberta pra qualquer conta logada
-- (a aba nem aparece pra quem é financeiro, mas isso é regra de tela,
-- não de banco); só a escrita fica restrita a admin.
create table if not exists marketing_metricas (
  id bigint generated by default as identity primary key,
  ano int not null,
  mes text not null,
  conta text not null check (conta in ('open','foco')),
  rede text not null check (rede in ('instagram','youtube','linkedin','tiktok','podtributar')),
  -- seguidores/inscritos/ouvintes (o que a rede chama de "audiência"),
  -- alcance/visualizações/reproduções do mês, e interações do mês —
  -- os três números que, juntos, dão pra calcular crescimento e
  -- engajamento sem pedir mais nada de quem lança.
  seguidores numeric,
  alcance numeric,
  interacoes numeric,
  created_at timestamptz not null default now()
);

alter table marketing_metricas enable row level security;

drop policy if exists "select any" on marketing_metricas;
create policy "select any" on marketing_metricas for select to authenticated
  using (true);

drop policy if exists "insert admin" on marketing_metricas;
create policy "insert admin" on marketing_metricas for insert to authenticated
  with check (current_user_is_admin());

drop policy if exists "update admin" on marketing_metricas;
create policy "update admin" on marketing_metricas for update to authenticated
  using (current_user_is_admin());

drop policy if exists "delete admin" on marketing_metricas;
create policy "delete admin" on marketing_metricas for delete to authenticated
  using (current_user_is_admin());

revoke all on marketing_metricas from anon;
grant select on marketing_metricas to authenticated;
grant insert, update, delete on marketing_metricas to authenticated;
grant usage on sequence marketing_metricas_id_seq to authenticated;
