-- ============================================================
-- Migração 27 — Marketing: Tráfego pago (campanhas)
-- ============================================================
-- Aplicada no banco como: marketing_campanhas
--
-- Diferente das redes (Instagram, YouTube...), tráfego pago não é "um
-- número por mês" — é uma campanha por vez, com um conjunto de métricas
-- de anúncio (investimento, alcance, cliques, leads...). Por isso é
-- tabela própria, não mais um `rede` dentro de marketing_metricas.
--
-- As métricas derivadas (Custo/MQL, CPC, CPL, CTR, CPM, Connect rate)
-- NÃO são colunas — são calculadas na tela a partir dos números brutos,
-- do mesmo jeito que a comissão por % se refaz sozinha em outras abas.
create table if not exists marketing_campanhas (
  id bigint generated by default as identity primary key,
  ano int not null,
  mes text not null,
  conta text not null check (conta in ('open','foco')),
  campanha text not null default '',
  gasto numeric,              -- Amount spent
  orcamento_diario numeric,   -- Orçamento diário
  alcance numeric,            -- Reach
  impressoes numeric,         -- Impressions
  cliques_link numeric,       -- Link clicks
  visitas_lp numeric,         -- Landing page views
  leads numeric,
  mql numeric,
  created_at timestamptz not null default now()
);

alter table marketing_campanhas enable row level security;

drop policy if exists "select any" on marketing_campanhas;
create policy "select any" on marketing_campanhas for select to authenticated
  using (true);

drop policy if exists "insert admin" on marketing_campanhas;
create policy "insert admin" on marketing_campanhas for insert to authenticated
  with check (current_user_is_admin());

drop policy if exists "update admin" on marketing_campanhas;
create policy "update admin" on marketing_campanhas for update to authenticated
  using (current_user_is_admin());

drop policy if exists "delete admin" on marketing_campanhas;
create policy "delete admin" on marketing_campanhas for delete to authenticated
  using (current_user_is_admin());

revoke all on marketing_campanhas from anon;
grant select on marketing_campanhas to authenticated;
grant insert, update, delete on marketing_campanhas to authenticated;
grant usage on sequence marketing_campanhas_id_seq to authenticated;
